def timeline(img, cur, t, a, sweep=None, season=0):
    NL, NLC = NODE_L[season], NODE_LC[season]
    if a <= 0: return
    base = np.asarray(img, np.float32)
    band = base[60:185, :, :].mean()
    if band > 90:
        k = min(0.55, (band - 90) / 160) * a
        rows = np.arange(0, 240, dtype=np.float32)
        wgt = (np.clip((rows - 20) / 50, 0, 1) * np.clip((235 - rows) / 60, 0, 1))[:, None, None] * k
        arr = base.copy(); arr[0:240] = arr[0:240] * (1 - wgt) + np.array([12, 18, 24]) * wgt
        img.paste(Image.fromarray(arr.astype(np.uint8)))
    dr = ImageDraw.Draw(img)
    def c(col, k=1.0): return tuple(int(v * a * k) for v in col)
    xs = [TX0 + i * TSTEP for i in range(6)]
    end = xs[-1] + 140
    curx = xs[int(cur) - 1] if cur >= 1 else TX0
    dr.line((TX0, TY, end - 20, TY), fill=c((90, 100, 110)), width=3)
    dr.polygon([(end, TY), (end - 22, TY - 9), (end - 22, TY + 9)], fill=c((90, 100, 110)))
    if sweep is not None:
        sx = lerp(TX0, end, sweep); dr.line((TX0, TY, sx, TY), fill=c((255, 205, 110)), width=4)
        dr.ellipse((sx - 8, TY - 8, sx + 8, TY + 8), fill=c((255, 235, 180)))
    elif cur > 1:
        dr.line((TX0, TY, curx, TY), fill=c((255, 205, 110), 0.8), width=4)
    for i, x in enumerate(xs):
        n = i + 1
        if sweep is not None: done = x <= lerp(TX0, end, sweep); iscur = False
        else: done = n < cur; iscur = abs(n - cur) < 0.5
        if iscur:
            pr = 0.5 + 0.5 * math.sin(t * 3)
            dr.ellipse((x - 24 - 4 * pr, TY - 24 - 4 * pr, x + 24 + 4 * pr, TY + 24 + 4 * pr), outline=c((255, 205, 110), 0.6), width=3)
            dr.ellipse((x - 14, TY - 14, x + 14, TY + 14), fill=c((255, 205, 110)))
            put(img, NLC[i], x, TY + 50, a)
        elif done:
            dr.ellipse((x - 9, TY - 9, x + 9, TY + 9), fill=c((220, 175, 90)))
